const chalk = require('chalk');
const fs = require('fs-extra');
const path = require('path');
const os = require('os');
const crypto = require('crypto');
const { exec } = require('child_process');
const { promisify } = require('util');
const execAsync = promisify(exec);
const QRCode = require('qrcode');

// Max length of an encoded project directory name before Claude Code
// truncates and appends a hash. Mirrors the constant in the Claude Code bundle.
const PROJECT_NAME_MAX = 200;

/**
 * SessionSharing - Handles exporting Claude Code sessions as downloadable context
 */
class SessionSharing {
  constructor(conversationAnalyzer) {
    this.conversationAnalyzer = conversationAnalyzer;
  }

  /**
   * Export conversation session as downloadable markdown file
   * @param {string} conversationId - Conversation ID to export
   * @param {Object} conversationData - Full conversation data object
   * @param {Object} options - Export options (messageLimit, etc.)
   * @returns {Promise<Object>} Export result with markdown content and filename
   */
  async exportSessionAsMarkdown(conversationId, conversationData, options = {}) {
    console.log(chalk.blue(`📥 Preparing session ${conversationId} for download...`));

    try {
      // 1. Get conversation messages
      const allMessages = await this.conversationAnalyzer.getParsedConversation(conversationData.filePath);

      // Limit messages to avoid large file sizes (default: last 100 messages)
      const messageLimit = options.messageLimit || 100;
      const messages = allMessages.slice(-messageLimit);

      // 2. Convert to markdown format
      const markdown = this.convertToMarkdown(messages, conversationData, {
        messageCount: messages.length,
        totalMessageCount: allMessages.length,
        wasLimited: allMessages.length > messageLimit
      });

      // 3. Generate filename
      const projectName = (conversationData.project || 'session').replace(/[^a-zA-Z0-9-_]/g, '-');
      const date = new Date().toISOString().split('T')[0];
      const filename = `claude-context-${projectName}-${date}.md`;

      console.log(chalk.green(`✅ Session exported successfully!`));
      console.log(chalk.gray(`📊 Exported ${messages.length} messages`));

      return {
        success: true,
        markdown,
        filename,
        messageCount: messages.length,
        totalMessageCount: allMessages.length,
        wasLimited: allMessages.length > messageLimit
      };
    } catch (error) {
      console.error(chalk.red('❌ Failed to export session:'), error.message);
      throw error;
    }
  }

  /**
   * Convert conversation messages to markdown format optimized for Claude Code
   * @param {Array} messages - Parsed conversation messages
   * @param {Object} conversationData - Conversation metadata
   * @param {Object} stats - Export statistics
   * @returns {string} Markdown formatted content
   */
  convertToMarkdown(messages, conversationData, stats) {
    const lines = [];

    // Header for Claude Code
    lines.push('# Previous Conversation Context\n');
    lines.push('> **Note to Claude Code**: This file contains the complete conversation history from a previous session. Read and understand this context to continue helping the user with their task.\n');
    lines.push(`**Project:** ${conversationData.project || 'Unknown'}`);
    lines.push(`**Date:** ${new Date().toISOString().split('T')[0]}`);
    lines.push(`**Messages in this export:** ${stats.messageCount}${stats.wasLimited ? ` (most recent from a total of ${stats.totalMessageCount})` : ''}`);
    lines.push('');
    lines.push('---');
    lines.push('');

    // Conversation
    lines.push('## 💬 Conversation History\n');

    messages.forEach((msg, index) => {
      const role = msg.role === 'user' ? '👤 User' : '🤖 Assistant';
      const timestamp = new Date(msg.timestamp).toLocaleString();

      lines.push(`### Message ${index + 1}: ${role}`);
      lines.push(`*${timestamp}*\n`);

      // Extract text content from message
      if (Array.isArray(msg.content)) {
        msg.content.forEach(block => {
          if (block.type === 'text') {
            lines.push(block.text);
          } else if (block.type === 'tool_use') {
            lines.push(`\`\`\`${block.name || 'tool'}`);
            lines.push(JSON.stringify(block.input || {}, null, 2));
            lines.push('```');
          } else if (block.type === 'tool_result') {
            lines.push('**Tool Result:**');
            lines.push('```');
            lines.push(typeof block.content === 'string' ? block.content : JSON.stringify(block.content, null, 2));
            lines.push('```');
          }
        });
      } else if (typeof msg.content === 'string') {
        lines.push(msg.content);
      }

      lines.push('');
      lines.push('---');
      lines.push('');
    });

    // Footer
    lines.push('\n---');
    lines.push('');
    lines.push('*Generated by Claude Chats Monitor*');

    return lines.join('\n');
  }

  /**
   * Export session data to standardized format
   * @param {string} conversationId - Conversation ID
   * @param {Object} conversationData - Conversation metadata
   * @param {Object} options - Export options
   * @returns {Promise<Object>} Exported session object
   */
  async exportSessionData(conversationId, conversationData, options = {}) {
    // Get all messages from the conversation
    const allMessages = await this.conversationAnalyzer.getParsedConversation(conversationData.filePath);

    // Limit messages to avoid large file sizes (default: last 100 messages)
    const messageLimit = options.messageLimit || 100;
    const messages = allMessages.slice(-messageLimit);

    // Convert parsed messages back to JSONL format (original Claude Code format)
    const jsonlMessages = messages.map(msg => {
      // Reconstruct original JSONL entry format
      const entry = {
        uuid: msg.uuid || msg.id,
        type: msg.role === 'assistant' ? 'assistant' : 'user',
        timestamp: msg.timestamp.toISOString(),
        message: {
          id: msg.id,
          role: msg.role,
          content: msg.content
        }
      };

      // Add model info for assistant messages
      if (msg.model) {
        entry.message.model = msg.model;
      }

      // Add usage info
      if (msg.usage) {
        entry.message.usage = msg.usage;
      }

      // Add compact summary flag if present
      if (msg.isCompactSummary) {
        entry.isCompactSummary = true;
      }

      return entry;
    });

    // Create export package
    const exportData = {
      version: '1.0.0',
      exported_at: new Date().toISOString(),
      conversation: {
        id: conversationId,
        project: conversationData.project || 'shared-session',
        created: conversationData.created,
        lastModified: conversationData.lastModified,
        messageCount: messages.length,
        totalMessageCount: allMessages.length,
        wasLimited: allMessages.length > messageLimit,
        tokens: conversationData.tokens,
        model: conversationData.modelInfo?.primaryModel || 'claude-sonnet-4-5-20250929'
      },
      messages: jsonlMessages,
      metadata: {
        exportTool: 'claude-chats-monitor',
        exportVersion: require('../package.json').version || '1.0.0',
        messageLimit: messageLimit,
        description: 'Claude Code session export'
      }
    };

    // Log information about exported messages
    if (allMessages.length > messageLimit) {
      console.log(chalk.yellow(`⚠️  Session has ${allMessages.length} messages, exporting last ${messageLimit} messages`));
    } else {
      console.log(chalk.gray(`📊 Exporting ${messages.length} messages`));
    }

    return exportData;
  }

  /**
   * Upload session to x0.at
   * @param {Object} sessionData - Session export data
   * @param {string} conversationId - Conversation ID for filename
   * @returns {Promise<string>} Upload URL
   */
  async uploadToX0(sessionData, conversationId) {
    const tmpDir = path.join(os.tmpdir(), 'claude-code-sessions');
    await fs.ensureDir(tmpDir);

    const tmpFile = path.join(tmpDir, `session-${conversationId}.json`);

    try {
      // Write session data to temp file
      await fs.writeFile(tmpFile, JSON.stringify(sessionData, null, 2), 'utf8');

      console.log(chalk.gray(`📁 Created temp file: ${tmpFile}`));
      console.log(chalk.gray(`📤 Uploading to x0.at...`));

      // Upload to x0.at using curl with form data
      // x0.at API: curl -F'file=@yourfile.png' https://x0.at
      // Response: Direct URL in plain text
      const { stdout, stderr } = await execAsync(
        `curl -s -F "file=@${tmpFile}" ${this.uploadUrl}`,
        { maxBuffer: 10 * 1024 * 1024 } // 10MB buffer
      );

      // x0.at returns URL directly in plain text
      const uploadUrl = stdout.trim();

      // Validate response
      if (!uploadUrl || !uploadUrl.startsWith('http')) {
        throw new Error(`Invalid response from x0.at: ${uploadUrl || stderr}`);
      }

      console.log(chalk.green(`✅ Uploaded to x0.at successfully`));
      console.log(chalk.yellow(`⚠️  Files kept for 3-100 days (based on size)`));
      console.log(chalk.gray(`🔓 Note: Files are not encrypted by default`));

      // Clean up temp file
      await fs.remove(tmpFile);

      return uploadUrl;
    } catch (error) {
      // Clean up temp file on error
      await fs.remove(tmpFile).catch(() => {});
      throw error;
    }
  }

  /**
   * Clone a session from a shared URL
   * Downloads the session and places it in the correct Claude Code location
   * @param {string} url - URL to download session from
   * @param {Object} options - Clone options
   * @returns {Promise<Object>} Result with session path
   */
  async cloneSession(url, options = {}) {
    console.log(chalk.blue(`📥 Downloading session from ${url}...`));

    try {
      // 1. Download session data
      const sessionData = await this.downloadSession(url);

      // 2. Validate session data
      this.validateSessionData(sessionData);

      console.log(chalk.green(`✅ Session downloaded successfully`));
      console.log(chalk.gray(`📊 Project: ${sessionData.conversation.project}`));
      console.log(chalk.gray(`💬 Messages: ${sessionData.conversation.messageCount}`));
      console.log(chalk.gray(`🤖 Model: ${sessionData.conversation.model}`));

      // 3. Install session in Claude Code directory
      const installResult = await this.installSession(sessionData, options);

      console.log(chalk.green(`\n✅ Session installed successfully!`));
      console.log(chalk.cyan(`📂 Location: ${installResult.sessionPath}`));

      // Show resume command (only conversation ID needed)
      const resumeCommand = `claude --resume ${installResult.conversationId}`;
      console.log(chalk.yellow(`\n💡 To continue this conversation, run:`));
      console.log(chalk.white(`\n   ${resumeCommand}\n`));
      console.log(chalk.gray(`   Or open Claude Code to see it in your sessions list`));

      return installResult;
    } catch (error) {
      console.error(chalk.red('❌ Failed to clone session:'), error.message);
      throw error;
    }
  }

  /**
   * Download session data from URL
   * @param {string} url - URL to download from
   * @returns {Promise<Object>} Session data
   */
  async downloadSession(url) {
    try {
      // Use curl to download (works with x0.at and other services)
      const { stdout, stderr } = await execAsync(`curl -L "${url}"`, {
        maxBuffer: 50 * 1024 * 1024 // 50MB buffer for large sessions
      });

      if (stderr && !stdout) {
        throw new Error(`Download failed: ${stderr}`);
      }

      // Parse JSON response
      const sessionData = JSON.parse(stdout);
      return sessionData;
    } catch (error) {
      if (error.message.includes('Unexpected token')) {
        throw new Error('Invalid session file - corrupted or not a Claude Code session');
      }
      throw error;
    }
  }

  /**
   * Validate session data structure
   * @param {Object} sessionData - Session data to validate
   * @throws {Error} If validation fails
   */
  validateSessionData(sessionData) {
    if (!sessionData.version) {
      throw new Error('Invalid session file - missing version');
    }

    if (!sessionData.conversation || !sessionData.conversation.id) {
      throw new Error('Invalid session file - missing conversation data');
    }

    if (!sessionData.messages || !Array.isArray(sessionData.messages)) {
      throw new Error('Invalid session file - missing or invalid messages');
    }

    if (sessionData.messages.length === 0) {
      throw new Error('Invalid session file - no messages found');
    }
  }

  /**
   * Install session in Claude Code directory structure
   * @param {Object} sessionData - Session data to install
   * @param {Object} options - Installation options
   * @returns {Promise<Object>} Installation result
   */
  async installSession(sessionData, options = {}) {
    const homeDir = os.homedir();
    const claudeDir = path.join(homeDir, '.claude');

    // Determine project directory
    const projectName = sessionData.conversation.project || 'shared-session';
    const projectDirName = this.sanitizeProjectName(projectName);

    // Create project directory structure
    // Format: ~/.claude/projects/-path-to-project/
    const projectDir = path.join(claudeDir, 'projects', projectDirName);
    await fs.ensureDir(projectDir);

    // Generate conversation filename with original ID
    const conversationId = sessionData.conversation.id;
    const conversationFile = path.join(projectDir, `${conversationId}.jsonl`);

    // Convert messages back to JSONL format (one JSON object per line)
    const jsonlContent = sessionData.messages
      .map(msg => JSON.stringify(msg))
      .join('\n');

    // Write conversation file
    await fs.writeFile(conversationFile, jsonlContent, 'utf8');

    console.log(chalk.gray(`📝 Created conversation file: ${conversationFile}`));

    // Create or update settings.json
    const settingsFile = path.join(projectDir, 'settings.json');
    const settings = {
      projectName: sessionData.conversation.project,
      projectPath: options.projectPath || process.cwd(),
      sharedSession: true,
      originalExport: {
        exportedAt: sessionData.exported_at,
        exportTool: sessionData.metadata?.exportTool,
        exportVersion: sessionData.metadata?.exportVersion
      },
      importedAt: new Date().toISOString()
    };

    await fs.writeFile(settingsFile, JSON.stringify(settings, null, 2), 'utf8');

    console.log(chalk.gray(`⚙️  Created settings file: ${settingsFile}`));

    return {
      success: true,
      sessionPath: conversationFile,
      projectDir,
      projectPath: settings.projectPath,
      conversationId,
      messageCount: sessionData.messages.length
    };
  }

  /**
   * Generate QR code for share command
   * @param {string} command - Command to encode in QR
   * @returns {Promise<Object>} QR code data (Data URL for web display)
   */
  async generateQRCode(command) {
    try {
      // Generate QR code as Data URL (for web display)
      const qrDataUrl = await QRCode.toDataURL(command, {
        errorCorrectionLevel: 'M',
        type: 'image/png',
        width: 300,
        margin: 2,
        color: {
          dark: '#000000',
          light: '#FFFFFF'
        }
      });

      return {
        dataUrl: qrDataUrl,
        command: command
      };
    } catch (error) {
      console.warn(chalk.yellow('⚠️  Could not generate QR code:'), error.message);
      return {
        dataUrl: null,
        command: command
      };
    }
  }

  // ---------------------------------------------------------------------------
  // Lossless session export / import (resume on another machine)
  //
  // Unlike exportSessionAsMarkdown/exportSessionData (which are lossy and drop the
  // fields Claude Code needs to reconstruct a session), these copy the original
  // JSONL transcript verbatim and, on import, rewrite only the machine-specific
  // fields (`cwd`, `sessionId`) so `claude --resume <id>` works on the target.
  // ---------------------------------------------------------------------------

  /**
   * Compute the ~/.claude/projects folder name Claude Code derives from a cwd.
   * Mirrors Claude Code's own algorithm exactly: replace every non-alphanumeric
   * character with '-', and if the result exceeds PROJECT_NAME_MAX chars, truncate
   * and append a base-36 hash of the ORIGINAL (untruncated) path.
   * @param {string} cwd - Absolute working directory path
   * @returns {string} Encoded directory name (e.g. "-Users-jane-my-project")
   */
  encodeProjectDirName(cwd) {
    const encoded = cwd.replace(/[^a-zA-Z0-9]/g, '-');
    if (encoded.length <= PROJECT_NAME_MAX) {
      return encoded;
    }
    return `${encoded.slice(0, PROJECT_NAME_MAX)}-${SessionSharing.hashPath(cwd)}`;
  }

  /**
   * 32-bit string hash matching Claude Code's project-name hashing, base-36 encoded.
   * @param {string} str - String to hash
   * @returns {string} Absolute hash in base-36
   */
  static hashPath(str) {
    let hash = 0;
    for (let i = 0; i < str.length; i++) {
      hash = ((hash << 5) - hash + str.charCodeAt(i)) | 0;
    }
    return Math.abs(hash).toString(36);
  }

  /**
   * Locate a session's raw JSONL transcript by session id.
   * Scans ~/.claude/projects/<encoded-cwd>/<id>.jsonl across all projects.
   * @param {string} sessionId - Session (conversation) id
   * @returns {Promise<string|null>} Absolute path to the .jsonl file, or null
   */
  async findSessionFile(sessionId) {
    const projectsRoot = path.join(os.homedir(), '.claude', 'projects');
    if (!(await fs.pathExists(projectsRoot))) {
      return null;
    }
    const projectDirs = await fs.readdir(projectsRoot);
    for (const dir of projectDirs) {
      const candidate = path.join(projectsRoot, dir, `${sessionId}.jsonl`);
      if (await fs.pathExists(candidate)) {
        return candidate;
      }
    }
    return null;
  }

  /**
   * Export a session losslessly into a portable package.
   * Reads the original JSONL transcript verbatim (every field, every line) so it
   * can be resumed on another machine. Unparseable lines are preserved raw.
   * @param {Object} params
   * @param {string} params.filePath - Path to the session .jsonl (optional if sessionId given)
   * @param {string} params.sessionId - Session id (used to locate file if filePath absent)
   * @param {string} [params.project] - Human-friendly project label
   * @returns {Promise<Object>} Portable session package
   */
  async exportSessionRaw({ filePath, sessionId, project } = {}) {
    let resolvedPath = filePath;
    if (!resolvedPath && sessionId) {
      resolvedPath = await this.findSessionFile(sessionId);
    }
    if (!resolvedPath || !(await fs.pathExists(resolvedPath))) {
      throw new Error(`Session transcript not found (sessionId=${sessionId || 'n/a'}, filePath=${filePath || 'n/a'})`);
    }

    const raw = await fs.readFile(resolvedPath, 'utf8');
    const lines = raw.split('\n');

    const parsedLines = [];
    let sourceCwd = null;
    let sourceSessionId = sessionId || null;
    for (const line of lines) {
      const trimmed = line.trim();
      if (!trimmed) continue;
      try {
        const obj = JSON.parse(trimmed);
        parsedLines.push(obj);
        if (!sourceCwd && typeof obj.cwd === 'string') sourceCwd = obj.cwd;
        if (!sourceSessionId && typeof obj.sessionId === 'string') sourceSessionId = obj.sessionId;
      } catch (e) {
        // Preserve anything we can't parse so the export stays lossless.
        parsedLines.push({ __raw: line });
      }
    }

    // Fall back to the filename for the session id (files are named <id>.jsonl).
    if (!sourceSessionId) {
      sourceSessionId = path.basename(resolvedPath, '.jsonl');
    }

    // Bundle any subagent (sidechain) transcripts stored under <projectDir>/<sessionId>/
    const sidechains = await this._collectSidechains(resolvedPath, sourceSessionId);

    return {
      format: 'claude-code-session',
      formatVersion: 1,
      exportedAt: new Date().toISOString(),
      source: {
        cwd: sourceCwd,
        sessionId: sourceSessionId,
        project: project || (sourceCwd ? path.basename(sourceCwd) : 'session'),
        lineCount: parsedLines.length
      },
      lines: parsedLines,
      sidechains,
      metadata: {
        exportTool: 'claude-code-chat-explorer',
        exportVersion: require('../package.json').version || '1.0.0',
        description: 'Lossless Claude Code session export (resumable)'
      }
    };
  }

  /**
   * Export EVERY local session into a single portable bundle (for transferring an
   * entire history to another machine). Walks ~/.claude/projects and exports each
   * top-level transcript losslessly (subagent sidechains included per session).
   * @returns {Promise<Object>} Bundle { format, sessions: [...] }
   */
  async exportAllSessions() {
    const projectsRoot = path.join(os.homedir(), '.claude', 'projects');
    const sessions = [];
    const errors = [];

    if (await fs.pathExists(projectsRoot)) {
      for (const dir of await fs.readdir(projectsRoot)) {
        const projectDir = path.join(projectsRoot, dir);
        const stat = await fs.stat(projectDir).catch(() => null);
        if (!stat || !stat.isDirectory()) continue;

        // Only top-level *.jsonl files are sessions; sidechains live in <id>/ subdirs
        // and are bundled by exportSessionRaw, so we must not treat them as sessions.
        for (const entry of await fs.readdir(projectDir)) {
          if (!entry.endsWith('.jsonl')) continue;
          const filePath = path.join(projectDir, entry);
          const fstat = await fs.stat(filePath).catch(() => null);
          if (!fstat || !fstat.isFile()) continue;
          try {
            const pkg = await this.exportSessionRaw({ filePath });
            sessions.push(pkg);
          } catch (e) {
            errors.push({ file: filePath, error: e.message });
          }
        }
      }
    }

    return {
      format: 'claude-code-session-bundle',
      formatVersion: 1,
      exportedAt: new Date().toISOString(),
      sessionCount: sessions.length,
      sessions,
      errors,
      metadata: {
        exportTool: 'claude-code-chat-explorer',
        exportVersion: require('../package.json').version || '1.0.0',
        description: 'Lossless bundle of all Claude Code sessions (resumable)'
      }
    };
  }

  /**
   * Import a bundle produced by exportAllSessions onto this machine.
   * Each session is placed back at its ORIGINAL cwd by default (reproducing the
   * source machine's project layout), optionally remapped via pathMap.
   * @param {Object} bundle - Bundle from exportAllSessions
   * @param {Object} options
   * @param {boolean} [options.keepSessionId=true] - Preserve original ids (default for bundles)
   * @param {boolean} [options.force=false] - Overwrite existing transcripts
   * @param {{from:string,to:string}} [options.pathMap] - Remap a cwd path prefix (e.g. old home → new home)
   * @param {string} [options.targetCwdOverride] - Force all sessions into one cwd (rare)
   * @returns {Promise<Object>} { imported, skipped, results }
   */
  async importBundle(bundle, options = {}) {
    if (!bundle || !Array.isArray(bundle.sessions)) {
      throw new Error('Invalid bundle: missing "sessions" array');
    }
    const keepSessionId = options.keepSessionId !== false; // default true
    const results = [];
    let imported = 0;
    let skipped = 0;

    for (const pkg of bundle.sessions) {
      const originalCwd = pkg.source?.cwd;
      const targetCwd = options.targetCwdOverride
        || this._remapCwd(originalCwd, options.pathMap);

      if (!targetCwd) {
        skipped++;
        results.push({ sessionId: pkg.source?.sessionId, skipped: true, reason: 'no cwd recorded in session' });
        continue;
      }

      try {
        const res = await this.importSession(pkg, {
          targetCwd,
          keepSessionId,
          force: !!options.force
        });
        imported++;
        results.push({ sessionId: res.sessionId, targetCwd: res.targetCwd, sessionFile: res.sessionFile, lineCount: res.lineCount });
      } catch (e) {
        skipped++;
        results.push({ sessionId: pkg.source?.sessionId, skipped: true, reason: e.message });
      }
    }

    return { imported, skipped, total: bundle.sessions.length, results };
  }

  /**
   * Apply an optional prefix remap to a cwd (e.g. /Users/old → /Users/new).
   * @param {string} cwd - Original cwd
   * @param {{from:string,to:string}} [pathMap] - Prefix mapping
   * @returns {string|null} Remapped cwd, or the original, or null if cwd falsy
   */
  _remapCwd(cwd, pathMap) {
    if (!cwd) return null;
    if (pathMap && pathMap.from && cwd.startsWith(pathMap.from)) {
      return path.resolve(pathMap.to + cwd.slice(pathMap.from.length));
    }
    return cwd;
  }

  /**
   * Collect subagent/sidechain transcripts that live alongside a session, if any.
   * @param {string} sessionFilePath - Path to the main .jsonl transcript
   * @param {string} sessionId - Session id
   * @returns {Promise<Array<{relPath: string, lines: Array}>>}
   */
  async _collectSidechains(sessionFilePath, sessionId) {
    const sideDir = path.join(path.dirname(sessionFilePath), sessionId);
    if (!(await fs.pathExists(sideDir))) {
      return [];
    }
    const results = [];
    const walk = async (dir) => {
      for (const entry of await fs.readdir(dir)) {
        const full = path.join(dir, entry);
        const stat = await fs.stat(full);
        if (stat.isDirectory()) {
          await walk(full);
        } else if (entry.endsWith('.jsonl')) {
          const content = await fs.readFile(full, 'utf8');
          const lines = content.split('\n')
            .map(l => l.trim())
            .filter(Boolean)
            .map(l => {
              try { return JSON.parse(l); } catch { return { __raw: l }; }
            });
          results.push({ relPath: path.relative(sideDir, full), lines });
        }
      }
    };
    await walk(sideDir);
    return results;
  }

  /**
   * Import a portable session package onto this machine so it can be resumed.
   * Rewrites machine-specific fields (`cwd`, `sessionId`) and writes the transcript
   * into the correct ~/.claude/projects/<encoded-cwd>/ location.
   * @param {Object} pkg - Package produced by exportSessionRaw (or a raw JSONL array wrapper)
   * @param {Object} options
   * @param {string} [options.targetCwd] - Absolute repo path on this machine (default: process.cwd())
   * @param {boolean} [options.keepSessionId] - Reuse the original id instead of minting a fresh one
   * @param {boolean} [options.force] - Overwrite if a transcript with the target id already exists
   * @returns {Promise<Object>} Result { sessionFile, projectDir, sessionId, targetCwd, lineCount }
   */
  async importSession(pkg, options = {}) {
    if (!pkg || !Array.isArray(pkg.lines) || pkg.lines.length === 0) {
      throw new Error('Invalid session package: no transcript lines found');
    }

    const targetCwd = path.resolve(options.targetCwd || process.cwd());
    const originalSessionId = pkg.source?.sessionId
      || (pkg.lines.find(l => l && typeof l.sessionId === 'string')?.sessionId);
    const newSessionId = options.keepSessionId && originalSessionId
      ? originalSessionId
      : crypto.randomUUID();

    const projectsRoot = path.join(os.homedir(), '.claude', 'projects');
    const projectDir = path.join(projectsRoot, this.encodeProjectDirName(targetCwd));
    await fs.ensureDir(projectDir);

    const sessionFile = path.join(projectDir, `${newSessionId}.jsonl`);
    if ((await fs.pathExists(sessionFile)) && !options.force) {
      throw new Error(`A session with id ${newSessionId} already exists at ${sessionFile}. Use force to overwrite.`);
    }

    // Rewrite only machine-specific fields; leave parentUuid/uuid/message/timestamp intact
    // so Claude Code's parentUuid chain still reconstructs correctly.
    const rewritten = pkg.lines.map(line => this._rewriteLine(line, targetCwd, newSessionId, originalSessionId));
    const jsonl = rewritten.map(l => (typeof l === 'string' ? l : JSON.stringify(l))).join('\n') + '\n';
    await fs.writeFile(sessionFile, jsonl, 'utf8');

    // Restore sidechain (subagent) transcripts under <projectDir>/<newSessionId>/
    let sidechainCount = 0;
    if (Array.isArray(pkg.sidechains) && pkg.sidechains.length > 0) {
      const sideDir = path.join(projectDir, newSessionId);
      for (const sc of pkg.sidechains) {
        const dest = path.join(sideDir, sc.relPath);
        await fs.ensureDir(path.dirname(dest));
        const lines = (sc.lines || []).map(l =>
          this._rewriteLine(l, targetCwd, newSessionId, originalSessionId));
        const content = lines.map(l => (typeof l === 'string' ? l : JSON.stringify(l))).join('\n') + '\n';
        await fs.writeFile(dest, content, 'utf8');
        sidechainCount++;
      }
    }

    return {
      success: true,
      sessionFile,
      projectDir,
      sessionId: newSessionId,
      originalSessionId: originalSessionId || null,
      targetCwd,
      lineCount: rewritten.length,
      sidechainCount
    };
  }

  /**
   * Rewrite machine-specific fields on a single transcript line.
   * @param {Object|string} line - Parsed line object, or a wrapper {__raw}
   * @param {string} targetCwd - New working directory
   * @param {string} newSessionId - New session id
   * @param {string} originalSessionId - Original session id (for raw-line substitution)
   * @returns {Object|string} Rewritten line (object) or raw string
   */
  _rewriteLine(line, targetCwd, newSessionId, originalSessionId) {
    if (line && typeof line === 'object' && typeof line.__raw === 'string') {
      // Best-effort id/cwd swap on lines we couldn't parse.
      let raw = line.__raw;
      if (originalSessionId) {
        raw = raw.split(originalSessionId).join(newSessionId);
      }
      return raw;
    }
    if (!line || typeof line !== 'object') {
      return line;
    }
    const out = { ...line };
    if ('cwd' in out) out.cwd = targetCwd;
    if ('sessionId' in out) out.sessionId = newSessionId;
    return out;
  }

  /**
   * Sanitize project name for directory usage
   * @param {string} projectName - Original project name
   * @returns {string} Sanitized name
   */
  sanitizeProjectName(projectName) {
    // Replace spaces and special chars with hyphens
    return projectName
      .replace(/[^a-zA-Z0-9-_]/g, '-')
      .replace(/-+/g, '-')
      .toLowerCase();
  }
}

module.exports = SessionSharing;
